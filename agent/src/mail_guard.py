"""Shared safety guard for every script that SENDS email on Bob's behalf.

WHY (Nov 2026 incident): outreach mailed Capital One's *Recruiting Accommodations*
inbox (disability/medical accommodation team). Its auto-reply mentioned "interview",
so the tracker classified it INTERVIEW_SCHEDULED and auto-replied with a calendar
link -> another auto-reply -> another calendar link ... a 17-message loop over 10 days,
each one opening a new accommodation request. Three rules prevent that class of bug:

  1. Never treat an AUTOMATED message as a human reply (headers + text).
  2. Never auto-reply / cold-email a ROLE or SENSITIVE mailbox.
  3. Never auto-reply to the same address twice within a cooldown (checked
     against Gmail's own Sent folder, so it works without any local state).
"""
import re
from datetime import datetime, timedelta

# Mailboxes that must NEVER receive outreach or auto-replies (substring match on
# the local part). Accommodation/legal/privacy inboxes are sensitive by nature.
SENSITIVE_LOCAL = (
    "accommodat", "disabilit", "ada", "eeo", "benefit", "payroll", "privacy",
    "legal", "compliance", "ethics", "security", "abuse", "fraud", "background",
)
ROLE_LOCAL = {
    "noreply", "no-reply", "donotreply", "do-not-reply", "notifications", "notification",
    "careers", "career", "jobs", "job", "hr", "talent", "recruiting", "recruitment",
    "recruiter", "hiring", "apply", "applications", "info", "support", "help", "admin",
    "team", "contact", "hello", "mailer-daemon", "postmaster", "system", "auto",
}

_AUTO_TEXT = [
    r"thank you for contacting", r"this (is an|is a) (automated|automatic)",
    r"automated (message|response|reply)", r"do not reply", r"please do not respond",
    r"auto-?reply", r"automatic reply", r"out of (the )?office", r"we('ve| have) received your (request|message|email|inquiry)",
    r"ticket (number|#)", r"case (number|#)", r"accommodation", r"this mailbox is not monitored",
]


def _local(addr: str) -> str:
    m = re.search(r"([\w.+-]+)@", (addr or "").lower())
    return m.group(1) if m else ""


def is_sensitive_mailbox(addr: str) -> bool:
    loc = _local(addr)
    tokens = set(re.split(r"[._+-]", loc))
    return any(s in loc for s in SENSITIVE_LOCAL if len(s) > 3) or "ada" in tokens or "eeo" in tokens


def is_role_mailbox(addr: str) -> bool:
    loc = _local(addr)
    tokens = set(re.split(r"[._+-]", loc))
    return loc in ROLE_LOCAL or bool(tokens & ROLE_LOCAL) or is_sensitive_mailbox(addr)


def is_automated(msg=None, subject: str = "", body: str = "") -> bool:
    """True if the message was generated by a machine (RFC 3834 + common headers + text)."""
    if msg is not None:
        get = lambda h: str(msg.get(h, "") or "").lower()
        if get("auto-submitted") and get("auto-submitted") != "no":
            return True
        if get("x-autoreply") or get("x-autorespond") or get("x-auto-response-suppress"):
            return True
        if get("precedence") in ("bulk", "junk", "list", "auto_reply"):
            return True
        if get("list-unsubscribe") or get("list-id"):
            return True
    text = f"{subject} {body}".lower()
    return any(re.search(p, text) for p in _AUTO_TEXT)


def may_auto_reply(addr: str, msg=None, subject: str = "", body: str = "") -> tuple:
    """(ok, reason). Rules 1 + 2. Rule 3 needs IMAP: see replied_recently()."""
    if is_sensitive_mailbox(addr):
        return False, "sensitive mailbox"
    if is_role_mailbox(addr):
        return False, "role mailbox"
    if is_blocked_domain(addr) or on_do_not_contact(addr):
        return False, "blocked domain / do-not-contact"
    if is_automated(msg, subject, body):
        return False, "automated message"
    return True, "ok"


def replied_recently(imap_conn, addr: str, days: int = 14) -> bool:
    """True if Bob's Sent folder already has a REPLY (Re:) TO addr within `days`.
    Fails CLOSED (returns True) on any error, so a broken check never sends."""
    try:
        since = (datetime.now() - timedelta(days=days)).strftime("%d-%b-%Y")
        for box in ('"[Gmail]/Sent Mail"', '"[Gmail]/Sent"', "Sent"):
            typ, _ = imap_conn.select(box, readonly=True)
            if typ == "OK":
                break
        else:
            return True
        # Count only previous REPLIES ("Re:"), not the original cold outreach.
        typ, data = imap_conn.search(None, f'(TO "{addr}" SINCE {since} SUBJECT "Re:")')
        return typ != "OK" or bool(data and data[0].split())
    except Exception:
        return True
    finally:
        try:
            imap_conn.select("INBOX")
        except Exception:
            pass


# Domains/subdomains that are HR help desks or ticket systems, never recruiters.
_BLOCKED_DOMAIN_TOKENS = ("hrhelp", "helpdesk", "servicedesk", "service-now", "servicenow",
                          "zendesk", "freshdesk", "ticket")


def is_blocked_domain(addr: str) -> bool:
    dom = (addr or "").lower().rpartition("@")[2]
    return any(t in dom for t in _BLOCKED_DOMAIN_TOKENS)


def on_do_not_contact(addr: str) -> bool:
    import os
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "do_not_contact.txt")
    try:
        lines = {l.strip().lower() for l in open(p) if l.strip() and not l.startswith("#")}
    except Exception:
        return False
    a = (addr or "").strip().lower()
    return a in lines or ("@" + a.rpartition("@")[2]) in lines
